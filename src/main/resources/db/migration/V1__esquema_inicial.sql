-- Sintaxis común a PostgreSQL (Supabase) y H2 en modo PostgreSQL (local).

create table usuario (
    id                     bigint generated by default as identity primary key,
    email                  varchar(160) not null,
    nombre                 varchar(120) not null,
    password_hash          varchar(100) not null,
    rol                    varchar(20)  not null,
    recibe_notificaciones  boolean      not null,
    token_baja             varchar(40)  not null,
    creado_en              timestamp with time zone not null,
    constraint uq_usuario_email unique (email),
    constraint uq_usuario_token_baja unique (token_baja)
);

create table salon (
    id           bigint generated by default as identity primary key,
    nombre       varchar(120) not null,
    direccion    varchar(200),
    capacidad    integer      not null,
    descripcion  varchar(1000)
);

create table evento (
    id                    bigint generated by default as identity primary key,
    titulo                varchar(150)  not null,
    descripcion           varchar(5000),
    fecha_inicio          timestamp     not null,
    salon_id              bigint references salon (id),
    precio                integer       not null,
    cupo_maximo           integer       not null,
    entradas_reservadas   integer       not null,
    max_por_compra        integer       not null,
    imagen_url            varchar(500),
    estado                varchar(20)   not null,
    recordatorio_enviado  boolean       not null,
    creado_en             timestamp with time zone not null,
    -- Última línea de defensa del cupo: aunque una ruta del código se saltara
    -- el bloqueo, la base rechaza vender de más.
    constraint ck_evento_cupo check (entradas_reservadas >= 0 and entradas_reservadas <= cupo_maximo),
    constraint ck_evento_precio check (precio >= 0)
);
create index ix_evento_estado_fecha on evento (estado, fecha_inicio);

create table orden (
    id                   bigint generated by default as identity primary key,
    codigo               varchar(26)  not null,
    id_sesion            varchar(61)  not null,
    usuario_id           bigint       not null references usuario (id),
    evento_id            bigint       not null references evento (id),
    cantidad             integer      not null,
    precio_unitario      integer      not null,
    monto                integer      not null,
    estado               varchar(20)  not null,
    token_webpay         varchar(100),
    codigo_autorizacion  varchar(20),
    tipo_pago            varchar(10),
    cuotas               integer,
    tarjeta_ultimos4     varchar(4),
    creada_en            timestamp with time zone not null,
    expira_en            timestamp with time zone not null,
    pagada_en            timestamp with time zone,
    constraint uq_orden_codigo unique (codigo),
    constraint uq_orden_token unique (token_webpay)
);
create index ix_orden_estado_expira on orden (estado, expira_en);
create index ix_orden_usuario on orden (usuario_id);
create index ix_orden_evento on orden (evento_id);

create table entrada (
    id          bigint generated by default as identity primary key,
    codigo      varchar(36) not null,
    orden_id    bigint      not null references orden (id),
    usada_en    timestamp with time zone,
    constraint uq_entrada_codigo unique (codigo)
);
create index ix_entrada_orden on entrada (orden_id);
